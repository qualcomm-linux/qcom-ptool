"""
Firehose XML of one LUN: what to write where, and the patches that fit
the GPT to the real disk size at flash time.

- ``rawprogramN.xml``: every partition image plus the primary and
  backup GPT;
- ``rawprogramN_WIPE_PARTITIONS.xml``: zeros over every partition and
  both GPTs;
- ``rawprogramN_BLANK_GPT.xml``: an empty GPT (forces EDL on next boot);
- ``patchN.xml``: the backup GPT location, the last usable LBA, a grown
  last partition and the CRCs, expressed in NUM_DISK_SECTORS;
- ``wipe_rawprogram_PHYn.xml``: zeros over the MBR and both GPTs.

Sector numbers below zero count from the end of the disk. Element and
attribute order are part of the output format consumed by flashing
tools and pinned by the checksum manifest.
"""

from __future__ import annotations

from xml.dom import minidom
from xml.etree.ElementTree import Comment, Element, SubElement, tostring

from qcom_ptool.layout import Geometry, Placement

AUTOGENERATED = "NOTE: This is an ** Autogenerated file **"
PATCH_NOTES = (
    "NOTE: Patching is in little endian format, i.e. 0xAABBCCDD will look like DD CC BB AA in the file or on disk",
    "NOTE: This file is used by Trace32 - So make sure to add decimals, i.e. 0x10-10=0, *but* 0x10-10.=6.",
)


def document(tag: str, *notes: str) -> Element:
    root = Element(tag)
    for note in notes:
        root.append(Comment(note))
    return root


def sector_note(geom: Geometry) -> str:
    return "NOTE: Sector size is %ibytes" % geom.sector


def render(root: Element) -> str:
    return minidom.parseString(tostring(root, "utf-8")).toprettyxml(indent="  ")


def program(
    root: Element, geom: Geometry, start: int, lun: int, num_sectors: int, filename: str,
    label: str, sparse: str = "false", readbackverify: str = "false",
    partofsingleimage: str = "false",
) -> None:
    """Write ``filename`` to ``num_sectors`` sectors at ``start``."""
    size_kb: object = num_sectors * geom.sector / 1024.0
    if num_sectors <= 0:
        num_sectors = size_kb = 0
    if start < 0:
        start_sector = "NUM_DISK_SECTORS%d." % start
        start_byte = "(%d*NUM_DISK_SECTORS)%d." % (geom.sector, start * geom.sector)
    else:
        start_sector = str(start)
        start_byte = hex(start * geom.sector)
    SubElement(root, "program", {
        "start_sector": start_sector,
        "size_in_KB": str(size_kb),
        "physical_partition_number": str(lun),
        "partofsingleimage": partofsingleimage,
        "file_sector_offset": "0",
        "num_partition_sectors": str(num_sectors),
        "readbackverify": readbackverify,
        "filename": filename,
        "sparse": sparse,
        "start_byte_hex": start_byte,
        "SECTOR_SIZE_IN_BYTES": str(geom.sector),
        "label": label,
    })


def patch(
    root: Element, geom: Geometry, start: object, offset: int, lun: int, size: int,
    value: str, filename: str, what: str,
) -> None:
    """Write ``value`` (an expression) over ``size`` bytes of ``filename``."""
    SubElement(root, "patch", {
        "start_sector": str(start),
        "byte_offset": str(offset),
        "physical_partition_number": str(lun),
        "size_in_bytes": str(size),
        "value": value,
        "filename": filename,
        "SECTOR_SIZE_IN_BYTES": str(geom.sector),
        "what": what,
    })


def zeros_name(sectors: int) -> str:
    return "zeros_%dsector%s.bin" % (sectors, "" if sectors == 1 else "s")


def lun_documents(
    placements: list[Placement], geom: Geometry, lun: int, num_entries: int,
) -> dict[str, Element]:
    """rawprogram, wipe, blank-GPT and patch documents of one LUN."""
    primary, backup = geom.primary_lbas, geom.backup_lbas
    gpt_main, gpt_backup = "gpt_main%d.bin" % lun, "gpt_backup%d.bin" % lun
    zeros = zeros_name(backup)

    raw = document("data", AUTOGENERATED, sector_note(geom))
    wipe = document("data", AUTOGENERATED, sector_note(geom))
    blank = document(
        "data", AUTOGENERATED,
        "NOTE: This file writes a VALID but EMPTY partition table to sector 0 **",
        sector_note(geom),
    )
    patches = document("patches", AUTOGENERATED, *PATCH_NOTES)

    def both(start: object, offset: int, size: int, value: str, image: str, disk_start: object,
             what: str) -> None:
        patch(patches, geom, start, offset, lun, size, value, image, what)
        patch(patches, geom, disk_start, offset, lun, size, value, "DISK", what)

    for j, p in enumerate(placements):
        label = p.entry["label"]
        if p.grown:
            entry_offset = 40 + j * 128
            offset = entry_offset % geom.sector
            backup_sector = entry_offset // geom.sector
            what = "Update last partition %d '%s' with actual size in %%s Header." % (j + 1, label)
            last_lba = "NUM_DISK_SECTORS-%d." % primary
            both(2 + backup_sector, offset, 8, last_lba, gpt_main, 2 + backup_sector,
                 what % "Primary")
            both(backup_sector, offset, 8, last_lba, gpt_backup,
                 "NUM_DISK_SECTORS-%d." % (backup - backup_sector), what % "Backup")
        program(raw, geom, p.first, lun, p.sectors, p.entry.get("filename", ""), label,
                sparse=p.entry.get("sparse", "false"))
        program(wipe, geom, p.first, lun, p.wipe_sectors, zeros, label)
        if j == 0:
            program(blank, geom, 0, lun, primary, "gpt_empty%d.bin" % lun, "PrimaryGPT")

    program(raw, geom, 0, lun, primary, gpt_main, "PrimaryGPT", partofsingleimage="true")
    program(wipe, geom, 0, lun, 1, zeros_name(1), "PrimaryGPT-MBR", partofsingleimage="true")
    program(wipe, geom, 1, lun, backup, zeros, "PrimaryGPT", partofsingleimage="true")
    program(raw, geom, -backup, lun, backup, gpt_backup, "BackupGPT", partofsingleimage="true")
    program(wipe, geom, -backup, lun, backup, zeros, "BackupGPT", partofsingleimage="true")

    header = backup - 1  # the backup header is the last sector of the backup image
    usable = "NUM_DISK_SECTORS-%d." % primary
    array_bytes = num_entries * 128
    both(1, 48, 8, usable, gpt_main, 1, "Update Primary Header with LastUseableLBA.")
    both(header, 48, 8, usable, gpt_backup, "NUM_DISK_SECTORS-1.",
         "Update Backup Header with LastUseableLBA.")
    patch(patches, geom, 1, 32, lun, 8, "NUM_DISK_SECTORS-1.", gpt_main,
          "Update Primary Header with BackupGPT Header Location.")
    patch(patches, geom, 1, 32, lun, 8, "NUM_DISK_SECTORS-1.", "DISK",
          "Update Primary Header with BackupGPT Header Location.")
    both(header, 24, 8, "NUM_DISK_SECTORS-1.", gpt_backup, "NUM_DISK_SECTORS-1.",
         "Update Backup Header with CurrentLBA.")
    both(header, 72, 8, "NUM_DISK_SECTORS-%d." % backup, gpt_backup, "NUM_DISK_SECTORS-1",
         "Update Backup Header with Partition Array Location.")
    both(1, 88, 4, "CRC32(2,%d)" % array_bytes, gpt_main, 1,
         "Update Primary Header with CRC of Partition Array.")
    patch(patches, geom, header, 88, lun, 4, "CRC32(0,%d)" % array_bytes, gpt_backup,
          "Update Backup Header with CRC of Partition Array.")
    patch(patches, geom, "NUM_DISK_SECTORS-1.", 88, lun, 4,
          "CRC32(NUM_DISK_SECTORS-%d.,%d)" % (backup, array_bytes), "DISK",
          "Update Backup Header with CRC of Partition Array.")
    for image in (gpt_main, "DISK"):
        patch(patches, geom, 1, 16, lun, 4, "0", image, "Zero Out Header CRC in Primary Header.")
        patch(patches, geom, 1, 16, lun, 4, "CRC32(1,92)", image,
              "Update Primary Header with CRC of Primary Header.")
    for start, image in ((header, gpt_backup), ("NUM_DISK_SECTORS-1.", "DISK")):
        crc_at = "NUM_DISK_SECTORS-1." if image == "DISK" else header
        patch(patches, geom, start, 16, lun, 4, "0", image, "Zero Out Header CRC in Backup Header.")
        patch(patches, geom, start, 16, lun, 4, "CRC32(%s,92)" % crc_at, image,
              "Update Backup Header with CRC of Backup Header.")

    return {
        "rawprogram%d.xml" % lun: raw,
        "rawprogram%d_WIPE_PARTITIONS.xml" % lun: wipe,
        "rawprogram%d_BLANK_GPT.xml" % lun: blank,
        "patch%d.xml" % lun: patches,
    }


def wipe_phy(geom: Geometry, phy: int) -> Element:
    """Zeros over the MBR and both GPTs of physical partition ``phy``."""
    backup = geom.backup_lbas
    root = document("data", AUTOGENERATED, sector_note(geom))
    program(root, geom, 0, phy, 1, zeros_name(1), "Overwrite MBR sector")
    program(root, geom, 1, phy, backup, zeros_name(backup), "Overwrite Primary GPT Sectors")
    program(root, geom, -backup, phy, backup, zeros_name(backup), "Overwrite Backup GPT Sectors")
    return root
